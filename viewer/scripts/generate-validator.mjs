import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const viewerRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(viewerRoot, "src/decision-view.v1.schema.json");
const outputPath = resolve(viewerRoot, "src/generated/decision-view-validator.mjs");
const schema = JSON.parse(await readFile(schemaPath, "utf8"));

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  strictTypes: false,
  code: { esm: true, source: true },
});
const validate = ajv.compile(schema);
const standalone = standaloneCode(ajv, validate).replace(
  /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
  "const $1 = (value) => Array.from(value).length;",
);
if (/\brequire\(|\bnew Function\(|\beval\(/.test(standalone)) {
  throw new Error("Generated validator contains a CSP-incompatible runtime construct");
}
const generated = `// Generated by scripts/generate-validator.mjs. Do not edit.\n${standalone}`;

let existing = "";
try {
  existing = await readFile(outputPath, "utf8");
} catch (error) {
  if (!(error && typeof error === "object" && "code" in error && error.code === "ENOENT")) {
    throw error;
  }
}

if (existing !== generated) {
  await writeFile(outputPath, generated, "utf8");
}
